import { Session, Discipline, Intensity } from './types'

function sportToDiscipline(sport: string): Discipline {
  switch (sport) {
    case 'Run': return 'run'
    case 'Swim': return 'swim'
    case 'Ride': return 'bike'
    case 'WeightTraining': return 'lift'
    case 'Yoga': return 'yoga'
    default: return 'other'
  }
}

function effortToIntensity(relativeEffort: number, maxSpeed: number): Intensity {
  if (relativeEffort >= 40) return 'hard'
  if (relativeEffort >= 15) return 'moderate'
  return 'easy'
}

function metersToKm(m: number) {
  return Math.round((m / 1000) * 100) / 100
}

